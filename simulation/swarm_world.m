function W = swarm_world()
% swarm_world —— 集群协同仿真：世界参数与场景定义
%
% 坐标系：x 向右，y 向上，单位：米(m)。时间单位：秒(s)。
% 该场景对应验收书“4.4 智能集群控制系统 / 4.5 仿真与试飞方案”的
% 阶梯式验证思想：质点运动学 + 人工势场(APF) + RRT 全局规划 + 动力学约束(MPC)。
%
% 本文件集中定义：
%   - 仿真与控制参数（步长、最大速度/加速度、安全距离、MPC预测步长）
%   - 禁飞区（穿越区域限制）：集群不可进入的圆形禁区
%   - 静态障碍物：需绕行的物理障碍
%   - 动态障碍物：沿直线往返运动的圆形障碍（演示动态避障）
%   - 9 架 UAV 的初始编队与目标编队

    % ===== 1. 仿真与控制基础参数 =====
    W.bounds   = [0 150; 0 90];   % [xmin xmax; ymin ymax] 仿真空域
    W.dt       = 0.10;            % 控制/仿真步长 (s)
    W.Tmax     = 70;              % 最大仿真时间 (s)
    W.vmax     = 9;               % 单机最大速度 (m/s)  —— 动力学包络上限
    W.amax     = 7;               % 单机最大加速度 (m/s^2) —— 姿控环可实现的最大指令
    W.dsafe    = 6.0;             % 机间安全距离 (m)
    W.N        = 10;              % MPC 预测步长

    % ===== 2. 禁飞区（穿越区域限制） =====
    % 每一行：[圆心x 圆心y 半径r]。集群轨迹不得进入这些圆（含安全余量）。
    % 设计意图：上、左下、右下各一处禁区，且在三排航道带（y∈[18,56]）之外，
    % 使 9 机编队能从中间“走廊”并行通过；禁区本身体现“穿越区域限制”。
    W.nofly = [ ...
        52, 72, 12;   % 上方禁区
       118,  6,  9;   % 右下方禁区
        28,  6,  8;   % 左下方禁区
    ];

    % ===== 3. 静态障碍物（物理障碍，需绕行） =====
    % 多数布置在航道带之外；个别（如(88,30)）布置在带边缘，迫使下排航道下探避让。
    W.static_obs = [ ...
        78, 72, 7;    % [x y r] 上方
       120, 72, 6;    % 上方
        48, 10, 6;    % 下方（带外）
        88, 30, 6;    % 中下（迫使下排下探避让）
    ];

    % ===== 4. 动态障碍物（沿直线往返运动的圆形障碍） =====
    % 用结构体数组描述，主循环中按速度更新并在边界反弹。
    % 两个垂直往返障碍位于航道带中部，演示动态避障/避撞。
    W.dyn_obs(1).pos = [70 40];  W.dyn_obs(1).vel = [0  7]; W.dyn_obs(1).r = 5;
    W.dyn_obs(2).pos = [105 40]; W.dyn_obs(2).vel = [0 -6]; W.dyn_obs(2).r = 5;

    % ===== 5. 9 架 UAV 初始编队（3x3 网格），位于左侧出发区 =====
    spacing = 14;
    start_grid = zeros(9,2);
    idx = 0;
    for iy = 0:2
        for ix = 0:2
            idx = idx + 1;
            start_grid(idx,:) = [18 + ix*spacing, 20 + iy*spacing];
        end
    end
    W.start = start_grid;

    % ===== 6. 目标编队：保持相对构型整体平移到右侧目标区 =====
    W.goal  = start_grid + [100 8];

    % ===== 7. RRT 全局规划参数 =====
    W.rrt.maxIter  = 4000;   % 最大采样次数
    W.rrt.step     = 6;      % 单步扩展步长
    W.rrt.goalBias = 0.10;   % 以 10% 概率直接采样目标（加速收敛）
    W.rrt.goalR    = 7;      % 视为抵达目标的距离阈值
    W.rrt.margin   = 2.5;    % 路径离障碍/禁区的安全余量

    % ===== 8. APF（人工势场）参数 =====
    W.apf.Katt     = 1.3;    % 目标吸引力增益
    W.apf.KrepObs  = 35;     % 静态/动态障碍排斥增益
    W.apf.KrepNofly= 70;     % 禁飞区排斥增益（更强）
    W.apf.KrepNei  = 40;     % 友机防撞排斥增益
    W.apf.d0Obs    = 11;     % 障碍影响半径
    W.apf.d0Nofly  = 20;     % 禁飞区影响半径
    W.apf.d0Nei    = W.dsafe + 5;  % 友机影响半径

    % ===== 9. MPC 权重 =====
    W.mpc.Q   = [2.0 0; 0 2.0];   % 位置跟踪
    W.mpc.R   = [0.4 0; 0 0.4];   % 控制（加速度）代价
    W.mpc.Rv  = [1.2 0; 0 1.2];   % 速度跟踪（阻尼）权重
    W.mpc.Qf  = [3.0 0; 0 3.0];   % 末端位置
    W.mpc.Wc  = 200;              % 机间防撞软惩罚
    W.mpc.Wo  = 150;              % 障碍/禁飞软惩罚
    W.mpc.margin = 3.0;           % MPC 障碍安全余量
    W.mpc.pairMargin = 1.5;       % 机间距离预测余量
end
